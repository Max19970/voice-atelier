const STORAGE_KEY = 'voice-atelier.lang';
const listeners = new Set();
let current = 'ru';

function readSaved() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch (_) {
    /* storage may be blocked */
  }
  return 'ru';
}

export function initLang() {
  current = readSaved();
  document.documentElement.lang = current;
  return current;
}

export function getLang() {
  return current;
}

export function setLang(next) {
  if (next !== 'ru' && next !== 'en') return;
  if (next === current) return;
  current = next;
  document.documentElement.lang = next;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch (_) {
    /* ignore */
  }
  for (const fn of listeners) fn(next);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Translate; unknown keys degrade to the key itself. */
export function t(key, params) {
  const dict = LOCALES[current] || LOCALES.ru;
  let value = dict[key];
  if (value === undefined) value = LOCALES.en[key];
  if (value === undefined) return key;
  if (!params) return value;
  return String(value).replace(/\{(\w+)\}/g, (match, name) => {
    const replacement = params[name];
    return replacement === undefined || replacement === null ? match : String(replacement);
  });
}

export function hasKey(key) {
  return key in LOCALES[current] || key in LOCALES.en;
}

const STAGE_KEYS = {
  queued: 'jobs.stageQueued',
  running: 'jobs.stageRunning',
  done: 'jobs.stageDone',
  failed: 'jobs.stageFailed',
  canceled: 'jobs.stageCanceled',
};

/** Localizes the few machine stage tokens the backend emits; free text passes through. */
export function stageLabel(stage) {
  if (!stage) return '';
  const key = STAGE_KEYS[String(stage).toLowerCase()];
  return key ? t(key) : String(stage);
}

/** Applies data-i18n / data-i18n-title attributes inside root. */
export function applyStatic(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.getAttribute('data-i18n'));
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    const text = t(element.getAttribute('data-i18n-title'));
    element.setAttribute('title', text);
    element.setAttribute('aria-label', text);
  }
}
